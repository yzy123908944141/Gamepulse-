def update_characters():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    updated = 0
    not_found = []

    for name, data in CHARACTERS_DATA.items():
        # 检查角色是否存在
        cur.execute("SELECT id FROM characters WHERE name = ?", (name,))
        row = cur.fetchone()

        if row is None:
            # 角色不存在，新建
            cur.execute("""
                INSERT INTO characters (name, game_name, personality_setting, background_lore, combat_style)
                VALUES (?, ?, ?, ?, ?)
            """, (
                name, "鸣潮",
                data.get("personality_setting", ""),
                data.get("background_lore", ""),
                data.get("combat_style", "")
            ))
            print(f"[新增] {name} - 已入库")
            updated += 1
        else:
            # 角色已存在，更新非空字段
            personality = data.get("personality_setting", "")
            background = data.get("background_lore", "")
            combat = data.get("combat_style", "")

            if personality or background or combat:
                cur.execute("""
                    UPDATE characters 
                    SET personality_setting = ?, background_lore = ?, combat_style = ?
                    WHERE name = ?
                """, (personality, background, combat, name))
                print(f"[更新] {name} (id={row[0]}) - 设定已更新")
                updated += 1
            else:
                print(f"[跳过] {name} (id={row[0]}) - 无数据更新")

    conn.commit()

    # 验证
    print("\n" + "=" * 60)
    print("验证结果")
    print("=" * 60)
    cur.execute("""
        SELECT id, name, 
               LENGTH(personality_setting) as p_len,
               LENGTH(background_lore) as b_len,
               LENGTH(combat_style) as c_len
        FROM characters 
        ORDER BY id
    """)
    rows = cur.fetchall()
    for row in rows:
        cid, cname, p_len, b_len, c_len = row
        p_len = p_len or 0
        b_len = b_len or 0
        c_len = c_len or 0
        status = "✅" if b_len > 0 else "⚠️"
        print(f"  {status} [{cid:2d}] {cname}: 性格({p_len}字) 背景({b_len}字) 战斗({c_len}字)")

    conn.close()
    print(f"\n✅ 完成，共处理 {updated} 个角色")
    print(f"📊 数据库共有 {len(rows)} 个角色")


if __name__ == "__main__":
    update_characters()
